package net.kirkanos.uptimekuma.core.model

import java.time.LocalDateTime
import java.time.LocalTime

/** How a maintenance window is scheduled (`strategy` in Kuma's `MaintenanceJSON`). */
enum class MaintenanceStrategy(
    val wire: String,
) {
    /** Active until paused by hand. */
    MANUAL("manual"),

    /** One window between two date-times. */
    SINGLE("single"),

    /** User-entered cron expression plus a duration. */
    CRON("cron"),

    /** Every N days in a daily time window. */
    RECURRING_INTERVAL("recurring-interval"),

    /** On selected weekdays in a daily time window. */
    RECURRING_WEEKDAY("recurring-weekday"),

    /** On selected days of the month in a daily time window. */
    RECURRING_DAY_OF_MONTH("recurring-day-of-month"),
    ;

    /** Uses the daily [Maintenance.startTime]..[Maintenance.endTime] window. */
    val isRecurring: Boolean get() = wire.startsWith("recurring-")

    companion object {
        /** Kuma's DB default is `single`. */
        fun fromWire(value: String?): MaintenanceStrategy = entries.firstOrNull { it.wire == value } ?: SINGLE
    }
}

/** Server-computed state of a maintenance (`status`, `Maintenance.getStatus`). */
enum class MaintenanceStatus(
    val wire: String,
) {
    UNDER_MAINTENANCE("under-maintenance"),
    SCHEDULED("scheduled"),
    INACTIVE("inactive"),
    ENDED("ended"),
    UNKNOWN("unknown"),
    ;

    companion object {
        fun fromWire(value: String?): MaintenanceStatus = entries.firstOrNull { it.wire == value } ?: UNKNOWN
    }
}

/** An entry of `daysOfMonth`: a day number (1..31) or `lastDay1`..`lastDay4`. */
sealed interface MaintenanceMonthDay {
    val wire: Any

    data class Day(
        val day: Int,
    ) : MaintenanceMonthDay {
        override val wire: Any get() = day
    }

    /** [n] = 1 is the last day of the month; Kuma only schedules `lastDay1` (cron `L`). */
    data class LastDay(
        val n: Int,
    ) : MaintenanceMonthDay {
        override val wire: Any get() = "lastDay$n"
    }

    companion object {
        const val LAST_DAY_PREFIX = "lastDay"
        val LAST: MaintenanceMonthDay = LastDay(1)
    }
}

/** A concrete window. Instants are epoch millis (UTC). */
data class MaintenanceTimeslot(
    val startMillis: Long,
    val endMillis: Long,
)

/**
 * A maintenance window as pushed in `maintenanceList` / returned by `getMaintenance`.
 * [startDate]/[endDate] and [startTime]/[endTime] are wall-clock values in [timezone].
 */
data class Maintenance(
    val id: Long,
    val title: String,
    val description: String = "",
    val strategy: MaintenanceStrategy,
    val active: Boolean = true,
    val status: MaintenanceStatus = MaintenanceStatus.UNKNOWN,
    val intervalDay: Int = 1,
    /** Start of the (effective) date range; required for [MaintenanceStrategy.SINGLE]. */
    val startDate: LocalDateTime? = null,
    val endDate: LocalDateTime? = null,
    /** Daily window for recurring strategies. */
    val startTime: LocalTime? = null,
    val endTime: LocalTime? = null,
    /** 0 = Sunday .. 6 = Saturday. */
    val weekdays: List<Int> = emptyList(),
    val daysOfMonth: List<MaintenanceMonthDay> = emptyList(),
    /** Cron as entered (strategy cron) or generated by Kuma (recurring); empty otherwise. */
    val cron: String = "",
    val durationMinutes: Int? = null,
    /** IANA zone actually used (`SAME_AS_SERVER` resolved). */
    val timezone: String = "UTC",
    /** Raw option: [TIMEZONE_SAME_AS_SERVER], [TIMEZONE_UTC] or an IANA name. */
    val timezoneOption: String = TIMEZONE_SAME_AS_SERVER,
    /** `+HH:mm` offset of [timezone] now. */
    val timezoneOffset: String = "+00:00",
    /** Current window (if running) and the next one; empty for manual. */
    val timeslots: List<MaintenanceTimeslot> = emptyList(),
) {
    /** The running or next window that ends after [nowMillis], if any. */
    fun nextTimeslot(nowMillis: Long): MaintenanceTimeslot? =
        timeslots.filter { it.endMillis > nowMillis }.minByOrNull { it.startMillis }

    companion object {
        const val TIMEZONE_SAME_AS_SERVER = "SAME_AS_SERVER"
        const val TIMEZONE_UTC = "UTC"
        const val TITLE_MAX_LENGTH = 150
    }
}

/** A status page as offered for maintenance linking (`statusPageList` / `getMaintenanceStatusPage`). */
data class MaintenanceStatusPage(
    val id: Long,
    val title: String,
    val slug: String? = null,
)

/** A maintenance with its linked monitors and status pages (`getMonitorMaintenance`, `getMaintenanceStatusPage`). */
data class MaintenanceDetail(
    val maintenance: Maintenance,
    val monitorIds: List<Long>,
    val statusPages: List<MaintenanceStatusPage>,
)

/** Editor state sent with `addMaintenance` / `editMaintenance` plus the link tables. */
data class MaintenanceDraft(
    /** `null` creates a new maintenance. */
    val id: Long? = null,
    val title: String = "",
    val description: String = "",
    val strategy: MaintenanceStrategy = MaintenanceStrategy.SINGLE,
    val active: Boolean = true,
    val intervalDay: Int = 1,
    val startDate: LocalDateTime? = null,
    val endDate: LocalDateTime? = null,
    val startTime: LocalTime = DEFAULT_START_TIME,
    val endTime: LocalTime = DEFAULT_END_TIME,
    val weekdays: Set<Int> = emptySet(),
    val daysOfMonth: Set<MaintenanceMonthDay> = emptySet(),
    val cron: String = DEFAULT_CRON,
    val durationMinutes: Int = DEFAULT_DURATION_MINUTES,
    val timezoneOption: String = Maintenance.TIMEZONE_SAME_AS_SERVER,
    val monitorIds: Set<Long> = emptySet(),
    val statusPageIds: Set<Long> = emptySet(),
) {
    companion object {
        /** Web UI defaults (`EditMaintenance.vue` init). */
        const val DEFAULT_CRON = "30 3 * * *"
        const val DEFAULT_DURATION_MINUTES = 60
        val DEFAULT_START_TIME: LocalTime = LocalTime.of(2, 0)
        val DEFAULT_END_TIME: LocalTime = LocalTime.of(3, 0)
    }
}

/** Outcome of saving a draft. [linkError] is set when the maintenance was stored but linking monitors/pages failed. */
data class MaintenanceSaveResult(
    val id: Long,
    val linkError: KumaError? = null,
)
